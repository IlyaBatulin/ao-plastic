export function applyCatalogSpecCorrections(
  productId: string,
  specifications: Record<string, unknown>
) {
  const patch = CATALOG_SPEC_CORRECTIONS[productId.toLowerCase()]
  if (!patch) return specifications

  const corrected = { ...specifications, ...patch.set }
  patch.remove?.forEach((key) => delete corrected[key])
  return corrected
}
