COMMENT ON COLUMN public.management_team.is_active IS 'Флаг активности (отображать или нет)';

-- ========== ШАГ 2: Создание индексов ==========
CREATE INDEX IF NOT EXISTS idx_management_team_sort_order ON public.management_team(sort_order);
CREATE INDEX IF NOT EXISTS idx_management_team_is_active ON public.management_team(is_active);
CREATE INDEX IF NOT EXISTS idx_management_team_active_sorted ON public.management_team(is_active, sort_order) WHERE is_active = true;

-- ========== ШАГ 3: Функция для автоматического обновления updated_at ==========
CREATE OR REPLACE FUNCTION update_management_team_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Создание триггера
DROP TRIGGER IF EXISTS trigger_update_management_team_updated_at ON public.management_team;
CREATE TRIGGER trigger_update_management_team_updated_at
  BEFORE UPDATE ON public.management_team
  FOR EACH ROW
  EXECUTE FUNCTION update_management_team_updated_at();

-- ========== ШАГ 4: Настройка Row Level Security (RLS) ==========
