-- ========== ШАГ 6: Создание функции для получения активных руководителей ==========
CREATE OR REPLACE FUNCTION get_active_management_team()
RETURNS TABLE (
  id UUID,
  full_name TEXT,
  "position" TEXT,
  bio TEXT,
  email TEXT,
  phone TEXT,
  image_url TEXT,
  sort_order INTEGER
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    mt.id,
    mt.full_name,
    mt."position",
    mt.bio,
    mt.email,
    mt.phone,
    mt.image_url,
    mt.sort_order
  FROM public.management_team mt
  WHERE mt.is_active = true
  ORDER BY mt.sort_order ASC, mt.created_at ASC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Комментарий к функции
