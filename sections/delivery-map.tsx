/** Нормализация названия региона из таблицы к ключу в REGION_COORDS */
function normalizeRegion(name: string): string {
  const s = name.trim()
  if (s === "Тверская обл") return "Тверская область"
  if (s === "Башкортостан") return "Республика Башкортостан"
  if (s === "Удмурская Республика") return "Удмуртская Республика"
  if (s.startsWith("Красноярск")) return "Красноярский край"
  if (s.includes("Якутия)")) return "Республика Саха (Якутия)"
  return s
}

